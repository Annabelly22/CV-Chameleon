// ----------------------------------------------------------------------------
// JSON HELPERS
// ----------------------------------------------------------------------------

function parseJSON(text) {
  const clean = text.replace(/```json\s*/gi, "").replace(/```\s*/g, "").trim();
  const start = clean.indexOf("{");
  const end = clean.lastIndexOf("}");
  if (start === -1 || end === -1) throw new Error("Model did not return JSON");
  return JSON.parse(clean.slice(start, end + 1));
}

// ----------------------------------------------------------------------------
// PASS 3: DETERMINISTIC AUDIT
// ----------------------------------------------------------------------------

const LEVEL_WORDS = ["senior", "sr", "principal", "staff", "lead", "head", "director", "manager", "vp", "chief"];
const BANNED = ["responsible for", "skilled in", "results-driven", "team player", "detail-oriented professional", "various", "etc."];
const norm = (s = "") => s.toLowerCase().replace(/[^a-z0-9+#./ ]/g, " ").replace(/\s+/g, " ").trim();
const words = (s = "") => norm(s).split(" ");

function resumeText(r) {
  const parts = [r.headerTitle, r.summary];
  (r.competencies || []).forEach((c) => parts.push(c.category, ...(c.items || [])));
  (r.experience || []).forEach((e) => {
    parts.push(e.title, e.companyContext);
    (e.bullets || []).forEach((b) => parts.push(typeof b === 'string' ? b : `${b.lead} ${b.rest}`));
  });
  (r.projects || []).forEach((p) => {
    parts.push(p.name, p.stack);
    (p.bullets || []).forEach((b) => parts.push(typeof b === 'string' ? b : `${b.lead} ${b.rest}`));
  });
  (r.additional || []).forEach((a) => parts.push(a));
  return norm(parts.filter(Boolean).join(" \n "));
}

export function auditResume(resume, analysis, master) {
  const violations = [];
  const text = resumeText(resume);

  // 1) Keyword coverage (weighted, claimable only)
  const claimable = (analysis.keywords || []).filter((k) => k.claimable);
  const gaps = (analysis.keywords || []).filter((k) => !k.claimable).map((k) => k.term);
  let hit = 0, total = 0;
  const missing = [];
  claimable.forEach((k) => {
    total += k.weight || 1;
    if (text.includes(norm(k.term))) hit += k.weight || 1;
    else missing.push(k.term);
  });
  const coverage = total ? Math.round((hit / total) * 100) : 100;

  // 2) Integrity vs master: company names, dates, seniority inflation
  const masterJobs = master.experience || [];
  (resume.experience || []).forEach((e) => {
    const m = masterJobs.find((j) => norm(j.company) === norm(e.company));
    if (!m) {
      violations.push(`Company "${e.company}" is not in the master resume. Use the exact master company name.`);
      return;
    }
    if ((m.dates || "").trim() !== (e.dates || "").trim()) {
      violations.push(`Dates for ${e.company} must be exactly "${m.dates}".`);
    }
    const before = new Set(words(m.title));
    const added = LEVEL_WORDS.filter((w) => words(e.title).includes(w) && !before.has(w));
    if (added.length) violations.push(`Title "${e.title}" adds seniority (${added.join(", ")}) not in master title "${m.title}".`);
  });

  // 3) Format rules
  const summaryWords = (resume.summary || "").split(/\s+/).filter(Boolean).length;
  if (summaryWords < 70 || summaryWords > 130) violations.push(`Summary is ${summaryWords} words; target 80-120.`);
  const nComp = (resume.competencies || []).length;
  if (nComp < 4 || nComp > 5) violations.push(`Use 4-5 competency categories (currently ${nComp}).`);
  (resume.experience || []).slice(0, 2).forEach((e) => {
    const n = (e.bullets || []).length;
    if (n < 4 || n > 6) violations.push(`${e.company}: top roles need 4-6 bullets (currently ${n}).`);
  });
  BANNED.forEach((p) => { if (text.includes(norm(p))) violations.push(`Remove banned phrase "${p}".`); });

  // 4) Gap leakage: unclaimable terms must not appear
  gaps.forEach((g) => { if (text.includes(norm(g))) violations.push(`"${g}" was marked not claimable but appears in the resume. Remove it.`); });

  return { coverage, missing, gaps, violations, pass: coverage >= 85 && violations.length === 0 };
}

// ----------------------------------------------------------------------------
// ELIGIBILITY GATE
// ----------------------------------------------------------------------------

function verdictFrom(analysis) {
  const blocked = (analysis.knockouts || []).filter((k) => k.candidateBlocked);
  const unmetHard = (analysis.hardRequirements || []).filter((r) => !r.candidateMeets);
  if (blocked.length) return { verdict: "SKIP", reasons: blocked.map((k) => `${k.type}: ${k.text}`) };
  if (unmetHard.length > 2) return { verdict: "APPLY_WITH_CAUTION", reasons: unmetHard.map((r) => r.text) };
  return { verdict: "APPLY", reasons: unmetHard.map((r) => r.text) };
}

