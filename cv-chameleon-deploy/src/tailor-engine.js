// ============================================================================
// CV CHAMELEON — TAILOR ENGINE v2
// Strategic Resume Generator methodology, rebuilt as a 3-pass pipeline:
//
//   PASS 1  ANALYZE   JD + master resume → requirements, knockouts, ranked
//                     keywords (split into "claimable" vs "gap"), positioning plan
//   PASS 2  TAILOR    Master resume + plan → tailored resume JSON
//   PASS 3  AUDIT     Deterministic checks in code (no LLM): keyword coverage,
//                     integrity vs master (companies, dates, seniority), format.
//                     If it fails, one REPAIR pass with the exact fixes needed.
//
// Contact info is NEVER generated by the model — it is injected from
// MASTER_RESUME.contact after generation (single source of truth).
// ============================================================================

