// MAIN PIPELINE
// ----------------------------------------------------------------------------

export async function tailorForJob({ job, masterResume, callModel, force = false, onStep = () => {} }) {
  const master = JSON.stringify(masterResume);
  const jd = `ROLE: ${job.title}\nCOMPANY: ${job.company}\nLOCATION: ${job.location || "Not stated"}\n\nJOB DESCRIPTION:\n${job.description}`;

  // PASS 1: analyze
  onStep("Analyzing job description");
  const analysis = parseJSON(await callModel({ system: ANALYZE_SYSTEM, user: `MASTER RESUME:\n${master}\n\n${jd}`, maxTokens: 2500 }));
  const gate = verdictFrom(analysis);
  if (gate.verdict === "SKIP" && !force) {
    return { verdict: gate.verdict, reasons: gate.reasons, analysis, resume: null, audit: null, brief: null };
  }

  // PASS 2: tailor
  onStep("Tailoring resume");
  const tailorUser = `MASTER RESUME:\n${master}\n\n${jd}\n\nANALYSIS & POSITIONING PLAN:\n${JSON.stringify(analysis)}\n\nReturn the tailored resume JSON.`;
  let resume = parseJSON(await callModel({ system: TAILOR_SYSTEM, user: tailorUser, maxTokens: 4000 }));

  // PASS 3: audit (+ one repair)
  onStep("Auditing keyword coverage and integrity");
  let audit = auditResume(resume, analysis, masterResume);
  if (!audit.pass) {
    onStep("Repairing weak spots");
    const fixes = [
      ...audit.violations,
      ...(audit.missing.length ? [`Work these claimable keywords in naturally (summary, top bullets or competencies): ${audit.missing.join(", ")}`] : []),
    ];
    const repaired = parseJSON(await callModel({
      system: REPAIR_SYSTEM,
      user: `${tailorUser}\n\nCURRENT RESUME:\n${JSON.stringify(resume)}\n\nFIX THESE PROBLEMS:\n- ${fixes.join("\n- ")}`,
      maxTokens: 4000,
    }));
    const reAudit = auditResume(repaired, analysis, masterResume);
    if (reAudit.violations.length <= audit.violations.length && reAudit.coverage >= audit.coverage) {
      resume = repaired;
      audit = reAudit;
    }
  }

  // Inject contact + name from master (never model-generated)
  resume.name = masterResume.name;
  resume.contact = masterResume.contact;
  resume.education = resume.education?.length ? resume.education : masterResume.education;

  // Filename
  const slug = (s, n) => (s || "").replace(/[^a-z0-9]+/gi, "_").replace(/^_|_$/g, "").slice(0, n);
  resume.filename = `${slug(analysis.role?.title || job.title, 40)}_${slug(masterResume.name || "Annabel_Otutu", 30)}_${slug(job.company, 25)}.pdf`;

  // Strategy brief
  onStep("Writing strategy brief");
  const brief = await callModel({
    system: BRIEF_SYSTEM,
    user: `${jd}\n\nANALYSIS:\n${JSON.stringify(analysis)}\n\nTAILORED RESUME:\n${JSON.stringify(resume)}\n\nAUDIT: coverage ${audit.coverage}%, gaps: ${audit.gaps.join(", ") || "none"}`,
    maxTokens: 1200,
  });

  return { verdict: gate.verdict, reasons: gate.reasons, analysis, resume, audit, brief };
}

